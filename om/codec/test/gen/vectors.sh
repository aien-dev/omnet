# Regenerates test/vectors/malformed.txt: the hand-made corpus of gen/oracle (oracle corpus) with
# the result Go go1.26.0 gives for each case. Test tooling only.
# Usage: sh om/codec/test/gen/vectors.sh   Environment: GO (default go).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../../.." && pwd)
out="$root/build/test/codec/gen"
go=${GO:-go}
mkdir -p "$out"
(cd "$here/oracle" && GOTOOLCHAIN=go1.26.0 "$go" build -o "$out/oracle" .)
"$out/oracle" corpus > "$out/corpus.txt"
grep -v '^#' "$out/corpus.txt" | "$out/oracle" > "$out/corpus.res"
v="$here/../vectors/malformed.txt"
{
	echo "# om/codec malformed-input corpus: OP ARG RESULT, in the driver's case and result format."
	echo "# Cases: test/gen/oracle 'corpus'. Results: Go $(GOTOOLCHAIN=go1.26.0 "$go" env GOVERSION)" \
		"encoding/base64, encoding/base32, encoding/hex and"
	echo "# the transcribed tailscale.com v1.102.0 AUMHash/NodePublic UnmarshalText (gen/oracle/main.go)."
	echo "# Generated by test/gen/vectors.sh. Lines starting with # name the input class that follows."
	awk 'NR == FNR { r[NR] = $0; next } /^#/ { print; next } { print $0, r[++i] }' \
		"$out/corpus.res" "$out/corpus.txt"
} > "$v"
echo "vectors: $(grep -vc '^#' "$v") cases written to $v"
