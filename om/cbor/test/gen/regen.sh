# Regenerates the oracle-made vector files of om/cbor into OUTDIR (default: test/vectors).
# Usage: sh om/cbor/test/gen/regen.sh GO [OUTDIR]
# GO is a Go toolchain >= 1.26.5 (the go directive of tailscale.com v1.102.0). The oracle imports
# tailscale.com/tka v1.102.0 and github.com/fxamacker/cbor/v2 v2.9.0 (go.sum pins both); the first
# run downloads them through the Go module proxy. Test referee only: nothing here is shipped.
set -eu
go=${1:?usage: regen.sh GO [OUTDIR]}
here=$(cd "$(dirname "$0")" && pwd)
out=${2:-$(dirname "$here")/vectors}
bin=$(mktemp -d)
trap 'rm -rf "$bin"' EXIT
(cd "$here/oracle" && "$go" build -o "$bin/oracle" .)
gov=$("$go" env GOVERSION)
o="$bin/oracle"

hdr() { # hdr FILE COMMAND DESCRIPTION
	{
		echo "# om/cbor vectors: $3"
		echo "# Generated by \`oracle $2\` (om/cbor/test/gen/oracle, $gov) from tailscale.com v1.102.0"
		echo "# (tka types and Serialize/Unserialize) and github.com/fxamacker/cbor/v2 v2.9.0."
		echo "# Regenerate: sh om/cbor/test/gen/regen.sh GO. Same seed, same bytes."
	} > "$1"
}

hdr "$out/tka-structs.txt" "gen 1 1200" "AUM, NodeKeySignature and State structures."
echo "# Line: TYPE HEX HASH K1. HEX = tka Serialize (CTAP2); HASH = AUM.Hash() for aum, BLAKE2s-256(HEX) otherwise; K1 = major:argument at key 1." >> "$out/tka-structs.txt"
"$o" gen 1 1200 >> "$out/tka-structs.txt"

hdr "$out/hostile.txt" "hostile" "hostile corpus, each case judged by tka's own Unserialize."
echo "# Line: CLASS TARGET WF ACCEPT RESER HEX DESCRIPTION. WF = Wellformed code (0 = well-formed); ACCEPT = TARGET.Unserialize accepted; RESER = tka Serialize after decoding, or -." >> "$out/hostile.txt"
"$o" hostile >> "$out/hostile.txt"

hdr "$out/fuzz.txt" "fuzz 1 2000" "random mutations (bit flips, byte changes, cuts, inserts, deletes) of generated structures."
echo "# Line: WF AUM NKS HEX. AUM/NKS = 1 when tka's AUM/NodeKeySignature Unserialize accepted the bytes." >> "$out/fuzz.txt"
"$o" fuzz 1 2000 >> "$out/fuzz.txt"

hdr "$out/utf8.txt" "utf8 1 2000" "single CBOR text strings; VALID from Go unicode/utf8.Valid."
echo "# Line: VALID HEX." >> "$out/utf8.txt"
"$o" utf8 1 2000 >> "$out/utf8.txt"
